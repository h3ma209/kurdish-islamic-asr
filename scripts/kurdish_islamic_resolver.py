def resolve_transcript(text: str) -> str:
    cleaned = text
    for pattern, repl in PHONETIC_REPLACEMENTS:
        cleaned = re.sub(pattern, repl, cleaned, flags=re.IGNORECASE)
    return normalize_ckb(cleaned)


if __name__ == "__main__":
    if len(sys.argv) > 1:
        in_path = Path(sys.argv[1])
        raw = in_path.read_text(encoding="utf-8")
        resolved = resolve_transcript(raw)
        out_path = in_path.with_name(f"{in_path.stem}_resolved.txt")
        out_path.write_text(resolved + "\n", encoding="utf-8")
        print(f"Resolved transcript written to {out_path}")
        print("\nPreview:\n", resolved[:400])
